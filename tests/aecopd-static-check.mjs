import fs from 'node:fs';
import assert from 'node:assert/strict';
const base='scenarios/aecopd';
const html=fs.readFileSync(base+'/index.html','utf8');
const data=fs.readFileSync(base+'/data/scenario-data.js','utf8');
const js=fs.readFileSync(base+'/scenario.js','utf8');
const manifest=fs.readFileSync(base+'/data/media-manifest.js','utf8');
assert.match(html,/scenario\.css/);
assert.match(html,/data\/scenario-data\.js/);
assert.match(html,/data\/media-manifest\.js/);
assert.match(html,/scenario\.js/);
for(const id of ['left-wall','center-wall','right-wall']) assert.match(html,new RegExp('id=["\\\']'+id+'["\\\']'));
assert.match(html,/AECOPD Scenario v1\.0/);
for(const label of ['Vital Signs','ABG','Oxygen Therapy','Lung Sound','CXR','Main Treatment']) assert.match(data,new RegExp(label));
for(const s of ['ACT1_START','ACT1_VITALS','ACT1_ABG','ACT1_OXYGEN','ACT1_LUNG_SOUND','ACT1_CXR','ACT1_TREATMENT','ACT2_OVERVIEW','ACT2_LUNG_SOUND','ACT2_ABG','ACT2_TREATMENT','ACT2_NIV_RESPONSE']) assert.match(data,new RegExp(s));
for(const v of ['T 37.0°C','BP 136/82','HR 110/min','RR 23/min','SpO₂ 90%','pH 7.39','PaCO₂ 55 mmHg','PaO₂ 65 mmHg','HCO₃⁻ 30 mEq/L','SaO₂ 91%','Nasal cannula 2 LPM','SpO₂ 89%','Bilateral expiratory wheezing','Hyperinflation with RLL infiltrates','pH 7.30','PaCO₂ 68','PaO₂ 52','HCO₃⁻ 34','SaO₂ 83%','Bilateral expiratory wheezing with decreased air entry','Acute-on-chronic hypercapnic respiratory failure with respiratory acidosis','Non-invasive Ventilation','Prednisolone 40 mg PO once daily × 5 days']) assert.ok(data.includes(v),'missing '+v);
for(const key of ['act1InitialPatient','act1EvidencePatient','act1PostTreatmentPatient','act2Patient','act2Monitor','nivPatient','nivMonitor','lungSound']) assert.match(manifest,new RegExp(key));
assert.doesNotMatch(manifest,/Patient[^\n]*(\.png|\.jpg|\.jpeg)/i);
assert.match(js,/createElement\(["']video["']\)/);
assert.match(js,/MEDIA_MANIFEST/);
assert.doesNotMatch(js,/😮‍💨|😌/);
console.log('AECOPD static checks passed');